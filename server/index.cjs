'use strict';
const {initializeApp,applicationDefault}=require('firebase-admin/app');
const {getFirestore,FieldValue}=require('firebase-admin/firestore');
const {getAuth}=require('firebase-admin/auth');
const {createParkingAction}=require('./parkingAction.cjs');
const {createApi}=require('./api.cjs');
const fs=require('node:fs');
const projectId=process.env.FIREBASE_PROJECT_ID||'smart-parking-hub';
const port=Number(process.env.PORT||3000);
if(!Number.isInteger(port)||port<1||port>65535)throw new Error('PORT không hợp lệ');
if(!process.env.GOOGLE_APPLICATION_CREDENTIALS)throw new Error('Chưa đặt GOOGLE_APPLICATION_CREDENTIALS. Xem README.');
const key=JSON.parse(fs.readFileSync(process.env.GOOGLE_APPLICATION_CREDENTIALS,'utf8'));
if(key.type!=='service_account'||key.project_id!==projectId)throw new Error('Service account không thuộc project '+projectId);
initializeApp({projectId,credential:applicationDefault()});
const auth=getAuth(), db=getFirestore();
const api=createApi({verifyToken:token=>auth.verifyIdToken(token,true),parkingAction:createParkingAction(db,FieldValue),projectId});
const cert=process.env.TLS_CERT_PATH,keyPath=process.env.TLS_KEY_PATH;
if(Boolean(cert)!==Boolean(keyPath))throw new Error('Cần cả TLS_CERT_PATH và TLS_KEY_PATH');
const server=cert?require('node:https').createServer({cert:fs.readFileSync(cert),key:fs.readFileSync(keyPath)},api):require('node:http').createServer(api);
server.requestTimeout=30000;server.headersTimeout=15000;
server.listen(port,process.env.HOST||'0.0.0.0',()=>console.log(`Smart Parking API | ${projectId} | ${cert?'HTTPS':'HTTP (LAN test only)'} | port ${port}`));
